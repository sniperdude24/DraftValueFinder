import { api, esc, trendArrow, signalBadge } from './api.js';
import { openProfile } from './profile.js';

const state = { pos: 'ALL', search: '', hideDrafted: false, sort: 'consensus', dir: 1 };

const COLS = [
  ['name', 'Player'], ['adp_rank', 'ADP'], ['expert_rank', 'Expert'], ['ai_rank', 'AI'],
  ['personal_rank', 'My Rank'], ['confidence', 'Conf'], ['trend', 'Trend'], ['signal', 'Signal'],
  ['bye', 'Bye'], ['actions', ''],
];

function sortVal(p, key) {
  if (key === 'name') return p.name.toLowerCase();
  if (key === 'trend') return { rising: 0, 'mixed-up': 1, flat: 2, 'mixed-down': 3, falling: 4 }[p.usage_trend] ?? 5;
  if (key === 'signal') return { signal: 0, emerging: 1 }[p.sleeper_state] ?? 2;
  if (key === 'consensus') return Math.min(p.adp_rank ?? 999, p.expert_rank ?? 999);
  const v = p[key];
  return v == null ? 9999 : v;
}

export async function renderBoard(el, refresh) {
  const { players, mode, week, stats_season } = await api.board();
  const season = mode === 'season';
  const drafted = players.filter(p => p.drafted).length;
  const mine = players.filter(p => p.mine).length;
  document.getElementById('draft-status').textContent = season
    ? `Week ${week ?? '?'} · Season mode · My roster: ${mine}`
    : `Pick ${drafted + 1} · Round ${Math.floor(drafted / 10) + 1} · My roster: ${mine}`;
  const takenLabel = season ? 'Taken' : 'Gone';
  const takenTitle = season ? 'Rostered by another team' : 'Someone else drafted them';
  const mineLabel = season ? 'My team' : 'My pick';

  const rows = players
    .filter(p => state.pos === 'ALL' || p.position === state.pos)
    .filter(p => !state.hideDrafted || !p.drafted || p.mine)
    .filter(p => !state.search || p.name.toLowerCase().includes(state.search))
    .sort((a, b) => {
      const va = sortVal(a, state.sort), vb = sortVal(b, state.sort);
      return (va < vb ? -1 : va > vb ? 1 : 0) * state.dir;
    });

  el.innerHTML = `
    <div class="toolbar">
      ${['ALL', 'QB', 'RB', 'WR', 'TE', 'K', 'DST'].map(p =>
        `<button class="posbtn ${state.pos === p ? 'active' : ''}" data-pos="${p}">${p}</button>`).join('')}
      <input type="search" id="board-search" placeholder="Search player…" value="${esc(state.search)}">
      <label><input type="checkbox" id="hide-drafted" ${state.hideDrafted ? 'checked' : ''}> ${season ? 'Hide rostered' : 'Hide drafted'}</label>
      <span class="spacer"></span>
      <button class="danger" id="reset-draft">Reset draft</button>
    </div>
    <table>
      <thead><tr>${COLS.map(([k, label]) =>
        `<th data-sort="${k}">${label}${state.sort === k ? (state.dir === 1 ? ' ↑' : ' ↓') : ''}</th>`).join('')}</tr></thead>
      <tbody>
        ${rows.map(p => `
          <tr class="${p.drafted ? 'drafted' : ''} ${p.mine ? 'mine' : ''}">
            <td class="name" data-id="${esc(p.id)}">${esc(p.name)}<span class="team">${esc(p.position)} · ${esc(p.team ?? 'FA')}</span>
              ${p.injury_status ? `<span class="badge inj">${esc(p.injury_status)}</span>` : ''}
              ${p.changed_team ? '<span class="badge newteam" title="on a different team than in the stats season">NEW TEAM</span>' : ''}</td>
            <td class="${season ? 'stale-col' : ''}" ${season ? 'title="Pre-draft ADP — stale during the season"' : ''}>${p.adp_rank ?? '—'}${p.adp_formatted ? `<span class="aid"> (${esc(p.adp_formatted)})</span>` : ''}</td>
            <td>${p.expert_rank ?? '—'}${p.expert_tier ? `<span class="aid"> T${p.expert_tier}</span>` : ''}</td>
            <td class="verdict-${esc(p.ai_verdict)}">${p.ai_rank ?? '—'}</td>
            <td>${p.personal_rank != null ? '#' + p.personal_rank : ''}</td>
            <td>${p.confidence != null ? p.confidence + '%' : '—'}</td>
            <td>${trendArrow(p.usage_trend)}</td>
            <td>${signalBadge(p.sleeper_state)}</td>
            <td>${p.bye ?? '—'}</td>
            <td>${p.drafted
              ? `<button class="rowbtn" data-undraft="${esc(p.id)}">Undo</button>`
              : `<button class="rowbtn mine" data-mine="${esc(p.id)}" title="On my roster">${mineLabel}</button>
                 <button class="rowbtn" data-gone="${esc(p.id)}" title="${takenTitle}">${takenLabel}</button>`}</td>
          </tr>`).join('')}
      </tbody>
    </table>
    <p class="small mt">AI rank & confidence are generated by this app's engine from usage evidence — they are not external data. ${season ? `Stats: ${esc(String(stats_season))} season, updated weekly · Expert: FantasyPros rest-of-season consensus · ADP is the pre-draft market (stale).` : 'ADP: FantasyFootballCalculator · Expert: FantasyPros consensus. Rows 201–250 are the sleeper watch list.'}</p>`;

  el.querySelectorAll('.posbtn').forEach(b => b.onclick = () => { state.pos = b.dataset.pos; refresh(); });
  // Search filters rows in place (no re-render, keeps focus).
  el.querySelector('#board-search').oninput = e => {
    state.search = e.target.value.toLowerCase();
    el.querySelectorAll('tbody tr').forEach(tr => {
      const name = tr.querySelector('td.name').textContent.toLowerCase();
      tr.style.display = name.includes(state.search) ? '' : 'none';
    });
  };
  el.querySelector('#hide-drafted').onchange = e => { state.hideDrafted = e.target.checked; refresh(); };
  el.querySelector('#reset-draft').onclick = async () => {
    if (confirm('Clear all draft picks?')) { await api.resetDraft(); refresh(); }
  };
  el.querySelectorAll('th[data-sort]').forEach(th => th.onclick = () => {
    const k = th.dataset.sort;
    if (k === 'actions') return;
    if (state.sort === k) state.dir *= -1; else { state.sort = k; state.dir = 1; }
    refresh();
  });
  el.querySelectorAll('td.name').forEach(td => td.onclick = () => openProfile(td.dataset.id, refresh));
  el.querySelectorAll('[data-mine]').forEach(b => b.onclick = async () => { await api.draft(b.dataset.mine, true); refresh(); });
  el.querySelectorAll('[data-gone]').forEach(b => b.onclick = async () => { await api.draft(b.dataset.gone, false); refresh(); });
  el.querySelectorAll('[data-undraft]').forEach(b => b.onclick = async () => { await api.undraft(b.dataset.undraft); refresh(); });
}
